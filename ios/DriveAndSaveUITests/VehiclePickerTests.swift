import XCTest

final class VehiclePickerTests: XCTestCase {
    override func setUpWithError() throws { continueAfterFailure = false }

    @MainActor
    func testSearchSaveRestoreUnsupportedVehicleAndAccountIsolation() throws {
        let app = XCUIApplication(); app.launchOffline()
        app.buttons["openProfile"].tap()
        app.scrollFullyIntoView(app.buttons["myVehicle"]); app.buttons["myVehicle"].tap()
        app.buttons["chooseVehicle"].tap()
        XCTAssertFalse(app.buttons["selectVehicleModel"].isEnabled)
        XCTAssertFalse(app.buttons["selectVehicleYear"].isEnabled)
        XCTAssertFalse(app.buttons["saveCatalogVehicle"].exists)
        app.buttons["selectVehicleBrand"].tap()
        XCTAssertTrue(app.buttons["vehicleOption-Mazda"].waitForExistence(timeout: 5))
        let search = app.searchFields.firstMatch
        search.tap(); search.typeText("zz")
        XCTAssertTrue(app.staticTexts["No results"].waitForExistence(timeout: 5))
        search.typeText(String(repeating: XCUIKeyboardKey.delete.rawValue, count: 2) + "Maz")
        XCTAssertFalse(app.buttons["vehicleOption-Tesla"].exists)
        app.buttons["vehicleOption-Mazda"].tap()
        app.buttons["selectVehicleModel"].tap()
        app.buttons["vehicleOption-MAZDA5"].tap()
        app.buttons["selectVehicleYear"].tap()
        app.buttons["vehicleOption-2012"].tap()
        XCTAssertTrue(app.staticTexts["selectedVehicleTitle"].waitForExistence(timeout: 5))
        XCTAssertEqual(app.staticTexts["selectedVehicleTitle"].label, "2012 Mazda MAZDA5")
        XCTAssertTrue(app.staticTexts["Combined MPG"].exists)
        app.buttons["selectVehicleYear"].tap(); app.buttons["vehicleOption-2012"].tap()
        XCTAssertTrue(app.staticTexts["selectedVehicleTitle"].exists, "Selecting the same year must keep the preview and Save action")
        XCTAssertTrue(app.buttons["saveCatalogVehicle"].exists)
        XCTAssertFalse(app.buttons["nav-Home"].exists)
        let preview = XCTAttachment(screenshot: app.screenshot()); preview.name = "Vehicle picker details"; preview.lifetime = .keepAlways; add(preview)
        app.scrollFullyIntoView(app.buttons["saveCatalogVehicle"]); app.buttons["saveCatalogVehicle"].tap()
        XCTAssertTrue(app.navigationBars["My Vehicle"].waitForExistence(timeout: 5))
        app.navigationBars.buttons.matching(identifier: "BackButton").firstMatch.tap()
        XCTAssertEqual(app.staticTexts["profileVehicleTitle"].label, "2012 Mazda MAZDA5")
        app.terminate(); app.launchOffline()
        app.buttons["openProfile"].tap()
        XCTAssertEqual(app.staticTexts["profileVehicleTitle"].label, "2012 Mazda MAZDA5")
        app.scrollFullyIntoView(app.buttons["myVehicle"]); app.buttons["myVehicle"].tap()
        app.scrollFullyIntoView(app.buttons["chooseVehicle"]); app.buttons["chooseVehicle"].tap()
        app.buttons["selectVehicleBrand"].tap(); app.buttons["vehicleOption-Mazda"].tap()
        app.buttons["selectVehicleModel"].tap(); app.buttons["vehicleOption-MAZDA5"].tap()
        app.buttons["selectVehicleYear"].tap(); app.buttons["vehicleOption-2012"].tap()
        app.buttons["selectVehicleBrand"].tap(); app.buttons["vehicleOption-Tesla"].tap()
        XCTAssertFalse(app.buttons["selectVehicleYear"].isEnabled)
        XCTAssertFalse(app.buttons["saveCatalogVehicle"].exists, "Old vehicle details must clear when brand changes")
        app.buttons["selectVehicleModel"].tap(); app.buttons["vehicleOption-Cybertruck AWD"].tap()
        app.buttons["selectVehicleYear"].tap(); app.buttons["vehicleOption-2026"].tap()
        XCTAssertTrue(app.staticTexts["vehicleEligibility"].waitForExistence(timeout: 5))
        XCTAssertEqual(app.staticTexts["vehicleEligibility"].label, "Fuel estimates unavailable for this vehicle")
        XCTAssertFalse(app.staticTexts["Combined MPG"].exists)
        app.scrollFullyIntoView(app.buttons["saveCatalogVehicle"]); app.buttons["saveCatalogVehicle"].tap()
        XCTAssertTrue(app.navigationBars["My Vehicle"].waitForExistence(timeout: 5))
        app.navigationBars.buttons.matching(identifier: "BackButton").firstMatch.tap()
        XCTAssertEqual(app.staticTexts["profileVehicleTitle"].label, "2026 Tesla Cybertruck AWD")
        app.openAdvancedSettings()
        let reset = app.buttons["resetTestAccount"]; app.scrollFullyIntoView(reset); reset.tap()
        app.buttons["Reset sign-in & choose a new nickname"].tap()
        let name = app.textFields["welcomeNickname"]; XCTAssertTrue(name.waitForExistence(timeout: 5))
        name.tap(); name.typeText("New Vehicle Driver\n"); app.buttons["welcomeRegister"].tap()
        XCTAssertTrue(app.buttons["openProfile"].waitForExistence(timeout: 5)); app.buttons["openProfile"].tap()
        XCTAssertFalse(app.staticTexts["profileVehicleTitle"].exists)
        XCTAssertTrue(app.staticTexts["No vehicle selected"].exists, "A different account must not inherit the previous driver's car")
    }
}
