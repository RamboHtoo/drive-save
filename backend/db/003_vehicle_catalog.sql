-- The EPA Test Car List (the repo's vehicle/ folder, model years 2010 on) and the car
-- picker built from it, with each car's fuel model parameters. Apply after the shared
-- schema; backend/scripts/load_vehicles.py fills the tables. Safe to rerun.
-- See docs/vehicle-catalog.md.

CREATE TABLE IF NOT EXISTS public.epa_test_car_files (
  file_name text PRIMARY KEY,
  sha256 text NOT NULL,
  model_year integer,
  row_count integer NOT NULL,
  skipped text, -- why the loader didn't read the file, e.g. the 2007-2009 layout
  loaded_at timestamptz NOT NULL DEFAULT now()
);

-- Every row of every file, under the column names in backend/services/epa_dataset.py.
-- make and model are the picker's brand and model name; null when the row isn't in it.
CREATE TABLE IF NOT EXISTS public.epa_test_cars (
  source_file text NOT NULL REFERENCES public.epa_test_car_files(file_name),
  source_row integer NOT NULL,
  make text,
  model text,
  model_year integer,
  manufacturer text,
  manufacturer_code text,
  represented_make text,
  represented_model text,
  test_vehicle_id text,
  configuration integer,
  displacement_l double precision,
  test_group text,
  vehicle_type text,
  rated_hp double precision,
  cylinders integer,
  engine_code text,
  transmission_code text,
  transmission text,
  gears integer,
  transmission_lockup text,
  drive_code text,
  drive text,
  overdrive_code text,
  overdrive text,
  etw_lb double precision,
  axle_ratio double precision,
  nv_ratio double precision,
  shift_indicator_code text,
  shift_indicator text,
  test_number text,
  test_originator text,
  analytically_derived text,
  adfe_test_number text,
  adfe_road_load_hp double precision,
  adfe_etw_lb double precision,
  adfe_nv_ratio double precision,
  test_procedure_code integer,
  test_procedure text,
  fuel_code integer,
  fuel text,
  test_category text,
  thc_g_per_mi double precision,
  co_g_per_mi double precision,
  co2_g_per_mi double precision,
  nox_g_per_mi double precision,
  pm_g_per_mi double precision,
  ch4_g_per_mi double precision,
  n2o_g_per_mi double precision,
  fe double precision,
  fe_unit text,
  fe_bag_1 double precision,
  fe_bag_2 double precision,
  fe_bag_3 double precision,
  fe_bag_4 double precision,
  target_a_lbf double precision,
  target_b_lbf_per_mph double precision,
  target_c_lbf_per_mph2 double precision,
  set_a_lbf double precision,
  set_b_lbf_per_mph double precision,
  set_c_lbf_per_mph2 double precision,
  aftertreatment_code text,
  aftertreatment text,
  police_emergency text,
  averaging_group_id text,
  averaging_weighting_factor double precision,
  averaging_method_code text,
  averaging_method text,
  dt_inertia_work_ratio double precision,
  dt_absolute_speed_change double precision,
  dt_energy_economy double precision,
  unmapped jsonb NOT NULL DEFAULT '{}'::jsonb, -- values that didn't fit their column, by original header
  PRIMARY KEY (source_file, source_row)
);
CREATE INDEX IF NOT EXISTS epa_test_cars_vehicle_idx ON public.epa_test_cars (make, model, model_year);

-- One row per brand, model and model year: the typical tested configuration's specs and
-- fuel model parameters (null when the model doesn't support the car), plus every
-- configuration in variants. make_key and model_key are the upper-case lookup keys.
CREATE TABLE IF NOT EXISTS public.vehicle_models (
  id uuid PRIMARY KEY,
  make text NOT NULL,
  model text NOT NULL,
  model_year integer NOT NULL,
  make_key text NOT NULL,
  model_key text NOT NULL,
  supported boolean NOT NULL,
  fuel_type text NOT NULL,
  vehicle_type text,
  test_vehicle_id text,
  test_configuration integer,
  variant_count integer NOT NULL,
  displacement_l double precision,
  cylinders integer,
  rated_hp double precision,
  transmission text,
  gears integer,
  drive text,
  etw_lb double precision,
  mass_kg double precision,
  nv_ratio double precision,
  axle_ratio double precision,
  target_a_lbf double precision,
  target_b_lbf_per_mph double precision,
  target_c_lbf_per_mph2 double precision,
  lab_ftp_mpg double precision,
  lab_hot_udds_mpg double precision,
  lab_hwy_mpg double precision,
  lab_us06_mpg double precision,
  label_city_mpg double precision,
  label_highway_mpg double precision,
  label_combined_mpg double precision,
  marginal_wheel_efficiency double precision,
  idle_rate_gal_per_hour double precision,
  coast_deceleration_g double precision,
  enrichment_start_fraction double precision,
  enrichment_max double precision,
  drivetrain_factor double precision,
  fuel_energy_j_per_gal double precision,
  parameters jsonb NOT NULL CHECK (jsonb_typeof(parameters) = 'array'),
  flags jsonb NOT NULL CHECK (jsonb_typeof(flags) = 'array'),
  fit_error jsonb,
  vehicle_profile jsonb,
  variants jsonb NOT NULL CHECK (jsonb_typeof(variants) = 'array'),
  catalog_version text NOT NULL,
  UNIQUE (make_key, model_key, model_year),
  CHECK (supported = (marginal_wheel_efficiency IS NOT NULL))
);

SELECT 'vehicle catalog tables ready' AS result;
